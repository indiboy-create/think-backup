<?php

/*
|--------------------------------------------------------------------------
| think-backup 数据库备份配置
|--------------------------------------------------------------------------
| 本配置文件会在服务注册时与包内默认配置合并，项目 config/backup.php
| 中的同名配置优先。所有路径均建议使用绝对路径，相对路径会基于项目
| 根目录解析。
|
| 本组件面向 MySQL / MariaDB，通过 ThinkPHP 的数据库连接执行备份与恢复。
| 不导出视图、触发器、存储过程和事件；如需完整迁移，请另行处理这些对象。
*/

$backup_env = static function (string $key, $default = null) {
    if (function_exists('env')) {
        return env($key, $default);
    }

    $value = getenv($key);

    return $value === false ? $default : $value;
};

$backup_runtime = function_exists('runtime_path')
    ? runtime_path('backup')
    : sys_get_temp_dir() . DIRECTORY_SEPARATOR . 'think-backup';

return [
    /*
    |--------------------------------------------------------------------------
    | 备份根目录
    |--------------------------------------------------------------------------
    | 所有备份目录、压缩包和恢复临时文件都保存在该目录下。组件会拒绝访问
    | 该目录之外的路径，防止路径穿越。目录必须可写。
    |
    | 默认：runtime/backup
    | 环境变量：BACKUP_PATH
    */
    'path' => $backup_env('BACKUP_PATH', $backup_runtime),

    /*
    |--------------------------------------------------------------------------
    | 数据库连接
    |--------------------------------------------------------------------------
    | connection：对应 config/database.php 中 connections 下的连接名。
    |             留空表示使用默认连接。调用时可用 connection 选项覆盖。
    | database  ：要备份或恢复的数据库名。留空表示使用连接配置中的
    |             database；仍为空时执行 SELECT DATABASE() 获取当前库。
    |             调用时可用 database 选项覆盖。
    */
    'connection' => $backup_env('BACKUP_CONNECTION', ''),
    'database' => $backup_env('BACKUP_DATABASE', ''),

    /*
    |--------------------------------------------------------------------------
    | 默认备份范围
    |--------------------------------------------------------------------------
    | prefix ：只备份以该前缀开头的表，留空表示不限制。通常可填写项目的
    |          表前缀，例如 "tp_"。
    | tables ：默认备份的表名数组，留空表示备份 prefix 匹配的全部表。
    | exclude：排除的表名数组，优先级高于 tables 与 prefix。
    |
    | 调用时传入的 tables 选项会覆盖这里的值，多个表名用英文逗号分隔或直接使用数组。
    */
    'prefix' => '',
    'tables' => [],
    'exclude' => [],

    /*
    |--------------------------------------------------------------------------
    | 备份内容
    |--------------------------------------------------------------------------
    | structure：是否导出表结构（DROP TABLE + CREATE TABLE）。
    | data     ：是否导出表数据。
    |
    | 两者都为 true 时生成完整备份；只导出结构可用于初始化空库；
    | 只导出数据时必须保证目标库已有对应表结构。
    */
    'structure' => true,
    'data' => true,

    /*
    |--------------------------------------------------------------------------
    | 分卷方式
    |--------------------------------------------------------------------------
    | mode：分卷依据，可选：
    |       size - 按文件大小分卷（默认）
    |       line - 按记录条数分卷
    |
    | size：单卷大小上限，单位 KB。数据超过该值后写入下一卷。
    |       一条记录本身超过上限时仍会完整写入当前卷，不会截断。
    | line：单卷最多包含的记录条数。结构语句不计入记录数。
    |
    | batch：每次从数据库读取的记录数，仅影响内存占用和查询次数，
    |        不影响最终分卷结果，默认 1000。
    */
    'mode' => 'size',
    'size' => 2048,
    'line' => 1000,
    'batch' => 1000,

    /*
    |--------------------------------------------------------------------------
    | INSERT 生成方式
    |--------------------------------------------------------------------------
    | insert：数据写入语句，可选：
    |         insert  - INSERT INTO（默认，遇到主键冲突会报错）
    |         replace - REPLACE INTO（遇到主键冲突会覆盖旧记录）
    |
    | complete_insert：是否在 INSERT 中写出字段名。true 生成
    |                  INSERT INTO `表` (`字段1`,`字段2`) VALUES (...)
    |                  false 生成 INSERT INTO `表` VALUES (...)
    |                  建议保持 true，表结构变化时更安全。
    |
    | hex：二进制字段处理方式，可选：
    |      none - 所有值按字符串转义
    |      blob - 仅对 blob、binary、varbinary、bit、geometry 等二进制
    |             类型输出 0x 十六进制（默认，推荐）
    |      all  - 所有非 NULL 值都输出 0x 十六进制
    |
    | ignore_auto_increment：恢复时忽略自增字段的备份值，格式为
    |                        "表名.字段名" 数组。例如 ['tp_user.id']。
    |                        配置后该字段在备份文件中写为 NULL，由 MySQL
    |                        重新分配自增值，适合希望重新编号的场景。
    |
    | charset：备份文件中的 SET NAMES 字符集。
    |          auto 表示读取数据库默认字符集（默认），也可填写 utf8mb4 等。
    */
    'insert' => 'insert',
    'complete_insert' => true,
    'hex' => 'blob',
    'ignore_auto_increment' => [],
    'charset' => 'auto',

    /*
    |--------------------------------------------------------------------------
    | 压缩设置
    |--------------------------------------------------------------------------
    | zip：备份完成后是否自动生成同名 .zip 压缩包。需要 PHP zip 扩展。
    | zip_level：压缩级别 0-9，0 表示不压缩，9 表示最大压缩。
    |            数字越大压缩率越高、耗时越长，默认 6。
    | zip_keep_directory：生成压缩包后是否保留原始备份目录。
    |                      true 保留（默认），false 删除目录只保留 zip。
    |
    | 恢复时可以直接传入 .zip 文件名，组件会解压到临时目录并在完成后清理。
    */
    'zip' => false,
    'zip_level' => 6,
    'zip_keep_directory' => true,

    /*
    |--------------------------------------------------------------------------
    | 文件与执行限制
    |--------------------------------------------------------------------------
    | permissions：新建备份目录的权限，默认 0755。仅在 Linux / macOS 生效。
    | time_limit：执行备份或恢复时设置的 PHP 超时秒数，0 表示不修改。
    | count_exact：是否使用 COUNT(*) 精确统计表记录数。
    |              false 时使用 SHOW TABLE STATUS 的估算值（更快，默认）；
    |              true 时逐表 COUNT(*)，结果准确但大表较慢。
    | include_views：是否一并导出视图。视图依赖基础表，恢复顺序可能失败，
    |                默认只导出基础表。
    | retain_days：clean() 方法默认清理多少天前的备份，0 表示不自动清理。
    */
    'permissions' => 0755,
    'time_limit' => 0,
    'count_exact' => false,
    'include_views' => false,
    'retain_days' => 0,
];